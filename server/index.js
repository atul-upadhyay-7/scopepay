import 'dotenv/config';
import {createApp} from './app.js';
import {createPayPal} from './paypal.js';
import {connectStore} from './store.js';
for(const name of ['PAYPAL_CLIENT_ID','PAYPAL_CLIENT_SECRET','MONGODB_URI'])if(!process.env[name])throw new Error(`Missing ${name}. Copy .env.example to .env and configure sandbox values locally.`);
if(process.env.PAYPAL_ENV && process.env.PAYPAL_ENV!=='sandbox')throw new Error('Only sandbox is supported.');
const store=await connectStore(process.env.MONGODB_URI,process.env.MONGODB_DB||'scopepay');
const app=createApp({store,paypal:createPayPal({clientId:process.env.PAYPAL_CLIENT_ID,clientSecret:process.env.PAYPAL_CLIENT_SECRET}),clientId:process.env.PAYPAL_CLIENT_ID,appOrigin:process.env.APP_ORIGIN});
const server=app.listen(Number(process.env.PORT)||8090,'127.0.0.1',()=>console.log('Sandbox API listening on http://127.0.0.1:'+(process.env.PORT||8090)));
process.on('SIGTERM',()=>server.close(async()=>{await store.close();process.exit(0);}));
